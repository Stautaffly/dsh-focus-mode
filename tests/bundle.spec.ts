/** Real shipped Web + external bundle composition; no model or network calls. */
import { readFileSync } from 'node:fs'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { expect, it } from 'vitest'
import { Context, FiberState } from '@deepseek-ai/cordis'
import { defineTool } from '@deepseek-ai/dsh-tools'
import Loader from '@deepseek-ai/cordis-plugin-loader'
import Include from '@deepseek-ai/cordis-plugin-include'
import Group from '@deepseek-ai/cordis-plugin-group'
import { applyEntryPatches } from '@deepseek-ai/cordis-plugin-include'
import { loadOverlayPatches, bundlePatchPaths } from '@deepseek-ai/dsh-app-boot'
import { provideCmdline } from '@deepseek-ai/dsh-cmdline'
import { SessionId } from '@deepseek-ai/dsh-session'
import { ToolCallId } from '@deepseek-ai/dsh-llm'
import * as Commands from '../src/exec.ts'
import * as Hybrid from '../src/hybrid.ts'

const repository = process.env.DSH_SOURCE!
const bundle = fileURLToPath(new URL('..', import.meta.url))
// Only test infrastructure resolves Host source. Runtime plugin imports remain
// public package names, and the shipped bundle is loaded as ordinary patches.
// Generated by vitest.config.ts from the explicitly selected host checkout.
const { sources, manifests } = await import('virtual:dsh-host-modules')

it.each([false, true])('inherits the registry tool set in the real Web composition (optional plugins: %s)', async withPlugins => {
  const home = await mkdtemp(join(tmpdir(), 'focus-bundle-'))
  const ctx = new Context()
  try {
    ctx.baseUrl = pathToFileURL(home).href + '/'
    await ctx.plugin(Loader)
    ctx.loader.builtins.include = Include
    ctx.loader.builtins.group = Group
    const modules = new Map<string, () => Promise<unknown>>()
    for (const [path, manifest] of Object.entries(manifests)) {
      const folder = dirname(path)
      const main = sources[`${folder}/src/index.ts`]
      if (main !== undefined) modules.set(manifest.name, main)
      for (const [source, load] of Object.entries(sources)) {
        if (source.startsWith(`${folder}/src/`)) modules.set(`${manifest.name}/${source.slice(`${folder}/src/`.length, -3)}`, load)
      }
    }
    modules.set('dsh-focus-mode/exec', async () => Commands)
    modules.set('dsh-focus-mode/hybrid', async () => Hybrid)
    modules.set('@deepseek-ai/cordis-plugin-timer', () => import('@deepseek-ai/cordis-plugin-timer'))
    ctx.loader.internal = {
      version: 'v2', async import(specifier: string) {
        const load = modules.get(specifier)
        if (load === undefined) throw new Error(`source fixture cannot resolve ${specifier}`)
        return load()
      },
    } as NonNullable<typeof ctx.loader.internal>
    ctx.provide('profileContext', {
      name: 'comparison', dir: home, patchPath: join(home, 'profile.patch.yml'),
      installAnchor: join(repository, 'apps/cli/package.json'), home, cwd: home,
      startedBundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app', 'dsh-focus-mode'], overlays: [], telemetryDisabledEnv: '1',
    })
    provideCmdline(ctx, { args: [], exit() {} })
    // Only the transport facade is replaced. Host behavior, presets and tool
    // plugins remain real, as in the upstream keyless Web preset e2e.
    ctx.provide('connection', { fetch: { register: () => () => {} }, rpc: { intercept: () => () => {} } } as never)
    const web = join(repository, 'packages/bundle/web-app')
    const webManifest = JSON.parse(readFileSync(join(web, 'package.json'), 'utf8'))
    const patches = [
      ...loadOverlayPatches('focus-test', join(repository, 'packages/bundle/base/cordis.patch.yml')),
      ...bundlePatchPaths(web, webManifest.dsh.bundle).flatMap(path => loadOverlayPatches('focus-test', path)),
      ...loadOverlayPatches('focus-test', join(bundle, 'cordis.patch.yml')),
      ...withPlugins ? ['agent-team-profile', 'session-search', 'tool-worktree', 'terminal-bundle'].flatMap(name =>
        loadOverlayPatches('focus-test', join(repository, 'packages/experimental', name, 'cordis.patch.yml'))) : [],
      ...['webserver', 'hmr', 'web-runtime', 'session-telemetry-otel', 'desktop-product-telemetry', 'product-analytics',
        'modules', 'connection', 'session-log-download', 'open-in-app', 'client-hmr', 'directory-picker', 'session-query-sqlite',
      ].map(id => ({ id, disabled: true })),
      { id: 'storage-json', config: { root: join(home, 'storages') } },
      { id: 'session-persistence-jsonl', config: { root: join(home, 'sessions') } },
      { id: 'attachment-local', config: { dshHome: home } },
      { id: 'skill-filesystem', config: { dshHome: home, agentsHome: join(home, 'agents') } },
      { id: 'agent-preset-registry', config: { default: 'standard' } },
      { id: 'sandbox-policy', config: { mode: 'danger-full-access', workspaceRoot: home } },
      { insert: [{ id: 'directory-picker-browse', name: '@deepseek-ai/dsh-host-directory-picker-browse' }] },
    ]
    const path = join(home, 'cordis.yml')
    await writeFile(path, JSON.stringify(applyEntryPatches([], patches)))
    await ctx.loader.create({ name: 'cordis:include', config: { path: pathToFileURL(path).href } })
    await ctx.loader.await()
    const presets = await ctx.agentPresets.list()
    const focus = presets.find(preset => preset.id === 'focus-mode')
    expect(focus, JSON.stringify(presets)).toBeDefined()
    expect(focus?.broken).toBeUndefined()
    expect(presets.map(preset => preset.id).sort()).toEqual(['cordis', 'focus-mode', 'minimal', 'ptc', 'standard'])
    expect(ctx.agentPresets.defaultId).toBe('standard')
    const handle = await ctx.agents.create({ sessionId: SessionId('external-focus'), meta: { cwd: home }, setup: agentCtx => ctx.agentPresets.mount(agentCtx, 'focus-mode').then(() => undefined) })
    try {
      const assembly = await ctx.systemPrompt.assemble({ scope: handle.agent })
      expect(assembly.tools.map(tool => tool.name).sort()).toEqual([...ctx.tools.schemas(handle.agent).map(tool => tool.name), 'run_code'].sort())
      await expect(JSON.stringify({
        tools: assembly.tools.map(tool => tool.name).sort(),
        sections: assembly.sections.map(section => section.name),
      }, null, 2) + '\n').toMatchFileSnapshot(withPlugins ? './snapshots/focus-with-plugins.json' : './snapshots/focus-model-input.json')
      const execute = (name: string, args: object, id: string) => ctx.tools.execute({
        agent: handle.agent, signal: new AbortController().signal,
        calls: [{ type: 'tool-call' as const, id: ToolCallId(id), name, arguments: JSON.stringify(args) }],
      })
      const program = await execute('run_code', {
        code: 'return await tools.exec_command({cmd: "printf FOCUS_REAL_PROGRAM"})',
        description: 'Run command through real program runtime',
      }, 'real-program')
      expect(program.results[0]?.result.isError, JSON.stringify(program)).not.toBe(true)
      expect(JSON.stringify(program)).toContain('FOCUS_REAL_PROGRAM')
      if (withPlugins) {
        const invoke = async (name: string, args: object, id: string) => {
          const result = await execute(name, args, id)
          expect(result.results[0]?.result.isError, JSON.stringify(result)).not.toBe(true)
          return result.results[0]!.result
        }
        const names = assembly.tools.map(tool => tool.name)
        const sdk = assembly.sections.find(section => section.name === 'tools:sdk')!.text
        const teamNames = ctx.tools.definitions(handle.agent).filter(tool => tool.name.startsWith('team_task_') || ['list_agents', 'spawn_teammate', 'send_message', 'wait_agent', 'interrupt_agent'].includes(tool.name)).map(tool => tool.name)
        expect(teamNames.length).toBeGreaterThan(5)
        for (const name of teamNames) { expect(names).toContain(name); expect(sdk).toContain(name) }
        expect(assembly.sections.some(section => section.name === 'team:policy')).toBe(true)
        expect(assembly.contexts.some(context => context.name === 'team:identity')).toBe(true)
        expect(JSON.stringify(await invoke('list_agents', {}, 'team-direct'))).toContain('lead')
        await invoke('team_task_create', { subject: 'PLUGIN_TASK_PROBE', description: 'Test only; no teammate or model runs.' }, 'team-task')
        expect(JSON.stringify(await invoke('run_code', { code: 'return await tools.team_task_list({})', description: 'Read the shared task board' }, 'team-program'))).toContain('PLUGIN_TASK_PROBE')
        expect(JSON.stringify(await invoke('run_code', { code: 'return await tools.list_agents({})', description: 'List the registered team members' }, 'team-roster-program'))).toContain('lead')
        for (const name of ['session_search', 'session_trace', 'session_event_search', 'session_event_trace', 'session_event_read', 'terminal_open', 'terminal_read', 'terminal_close', 'create_worktree', 'working_directory']) {
          expect(names).toContain(name)
          expect(sdk).toContain(name)
        }
        await invoke('session_search', { query: 'nonexistent-focus-fixture-marker' }, 'session-direct')
        await invoke('run_code', { code: 'return await tools.session_trace({})', description: 'Read this session lineage' }, 'session-program')
        const opened = await invoke('terminal_open', { type: 'shell' }, 'terminal-direct')
        const terminal = opened.value as { sessionId: string }
        await invoke('run_code', { code: `return await tools.terminal_read({sessionId:${JSON.stringify(terminal.sessionId)}})`, description: 'Read the external terminal' }, 'terminal-program')
        await invoke('terminal_close', { sessionId: terminal.sessionId }, 'terminal-close')
        const repo = join(home, 'repository')
        await mkdir(repo)
        await writeFile(join(repo, 'fixture.txt'), 'worktree fixture\n')
        execFileSync('git', ['init', repo], { stdio: 'ignore' })
        execFileSync('git', ['-C', repo, 'add', '.'], { stdio: 'ignore' })
        execFileSync('git', ['-C', repo, '-c', 'user.name=Focus Test', '-c', 'user.email=focus@example.test', 'commit', '-m', 'fixture'], { stdio: 'ignore' })
        await invoke('working_directory', { cd: repo }, 'directory-direct')
        await invoke('create_worktree', { name: 'direct-addon-probe' }, 'worktree-direct')
        await invoke('run_code', { code: 'return await tools.create_worktree({name:"program-addon-probe"})', description: 'Create a temporary test checkout' }, 'worktree-program')
        // Plugin removal must withdraw both its prompt and its scoped tools.
        const entry = [...ctx.loader.entries()].find(entry => entry.options.id === 'tool-agent-team')!
        expect(entry.fiber?.state).toBe(FiberState.ACTIVE)
        await entry.update({ disabled: true })
        await ctx.loader.await()
        const after = await ctx.systemPrompt.assemble({ scope: handle.agent })
        expect(after.tools.map(tool => tool.name)).not.toContain('list_agents')
        expect(after.sections.some(section => section.name === 'team:policy')).toBe(false)
        expect(after.contexts.some(context => context.name === 'team:identity')).toBe(false)
        expect((await execute('list_agents', {}, 'removed-team')).results[0]?.result.isError).toBe(true)
        expect((await execute('run_code', { code: 'return await tools.list_agents({})', description: 'Try removed team tools' }, 'removed-team-program')).results[0]?.result.isError).toBe(true)
      }
    } finally { await handle.dispose() }
  } finally {
    await ctx.fiber.dispose()
    await rm(home, { force: true, recursive: true })
  }
}, 120000)
